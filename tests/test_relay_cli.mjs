import { test } from "node:test";
import assert from "node:assert/strict";
import { chmodSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
const cli = new URL("../scripts/relay/send_request.mjs", import.meta.url).pathname;
const writer = new URL("../scripts/relay/record_approval.mjs", import.meta.url).pathname;
test("request CLI requires recorded ids and sends envelope via fake Herdr", async () => {
  mkdirSync("scratch", { recursive: true });
  const root = mkdtempSync(join(process.cwd(), "scratch/relay-cli-"));
  const profile = join(root, "profile"); mkdirSync(join(profile, "config"), { recursive: true });
  writeFileSync(join(profile, "config/relay-authority.v1.json"), JSON.stringify({ relayers: [{ relayer: "bot", channel: "chat", maxTier: 1 }] }));
  const input = join(root, "approval.json");
  writeFileSync(input, JSON.stringify({ kind: "relay", relayer: "bot", channel: "chat", sourceMessageId: "42", quote: "Approve work", quotedQuestion: "May I work?", givenAt: new Date(Date.now() - 1000).toISOString(), tier: 1, scope: { repo: "example", actions: ["spawn"] } }));
  const written = spawnSync(process.execPath, [writer, profile, input], { encoding: "utf8" });
  assert.equal(written.status, 0, written.stderr);
  const entry = { id: written.stdout.trim() };
  const request = join(root, "request.txt"); writeFileSync(request, "Please proceed.");
  const bin = join(root, "bin"); mkdirSync(bin);
  const executable = join(bin, "herdr");
  writeFileSync(executable, '#!/usr/bin/env node\nimport { appendFileSync } from "node:fs";\nappendFileSync(process.env.FAKE_HERDR_LOG, JSON.stringify(process.argv.slice(2))+"\\n");\n');
  chmodSync(executable, 0o755);
  const log = join(root, "herdr.log");
  const args = [cli, profile, root, "w1:p1", "bot", entry.id, request];
  const env = { ...process.env, PATH: `${bin}:${process.env.PATH}`, FAKE_HERDR_LOG: log };
  const sent = spawnSync(process.execPath, args, { encoding: "utf8", env });
  assert.equal(sent.status, 0, sent.stderr);
  const calls = readFileSync(log, "utf8").trim().split("\n").map(JSON.parse);
  assert.equal(calls.length, 2);
  assert.match(calls[0][3], /^\[relay:v1 ledger=.* relayer=bot\]\nPlease proceed\./);
  assert.deepEqual(calls[1], ["pane", "send-keys", "w1:p1", "enter"]);
  const rejected = spawnSync(process.execPath, [cli, profile, root, "w1:p1", "bot", "missing", request], { encoding: "utf8", env });
  assert.equal(rejected.status, 1);
  assert.equal(readFileSync(log, "utf8").trim().split("\n").length, 2);
});
